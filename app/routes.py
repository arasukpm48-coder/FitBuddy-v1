FALLBACK_TIP = (
    "Drink water through the day, include protein and vegetables in your meals, "
    "and get 7-9 hours of sleep to help your body recover."
)
DB_ERROR = "Sorry, something went wrong while accessing the database. Please try again."

# ---------- Helpers to display a plan nicely in HTML ----------

DAY_PATTERN = re.compile(r"^\s*day\s*([1-7])\s*[:\-–—.]?\s*(.*)$", re.IGNORECASE | re.MULTILINE)


def _parse_line(raw: str):
    line = raw.strip()
    if not line:
        return None
    bullet = line.startswith("- ")
    if bullet:
        line = line[2:].strip()
    label = None
    if not bullet and ":" in line:
        head, _, rest = line.partition(":")
        if 0 < len(head) <= 25:
            label, line = head.strip(), rest.strip()
    return {"bullet": bullet, "label": label, "text": line}


def plan_days(plan_text):
    """Jinja filter: split plan text into a list of day cards."""
    if not plan_text:
        return []
    text = str(plan_text)
    matches = list(DAY_PATTERN.finditer(text))
    if not matches:
        lines = [x for x in (_parse_line(r) for r in text.splitlines()) if x]
        return [{"title": "Workout Plan", "lines": lines}]

    days = []
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        focus = match.group(2).strip()
        title = f"Day {match.group(1)}" + (f" – {focus}" if focus else "")
        lines = [x for x in (_parse_line(r) for r in text[match.end():end].splitlines()) if x]
        days.append({"title": title, "lines": lines})
    return days


templates.env.filters["plan_days"] = plan_days


def _friendly_validation(exc: ValidationError) -> str:
    parts = []
    for err in exc.errors():
        field = str(err["loc"][0]).replace("_", " ").title() if err["loc"] else "Input"
        parts.append(f"{field}: {err['msg']}")
    return " | ".join(parts)


def render_index(request: Request, error: str | None = None, form: dict | None = None,
                 status_code: int = 200):
    return templates.TemplateResponse(
        request,
        "index.html",
        {"goals": GOALS, "intensities": INTENSITIES, "error": error, "form": form or {}},
        status_code=status_code,
    )


def render_result(request: Request, user: UserWorkout, message: str | None = None,
                  error: str | None = None, status_code: int = 200):
    return templates.TemplateResponse(
        request,
        "result.html",
        {"user": user, "message": message, "error": error},
        status_code=status_code,
    )


# ---------- Routes ----------

@router.get("/", response_class=HTMLResponse)
def home(request: Request):
    """Show the main input form."""
    return render_index(request)


@router.post("/generate-workout", response_class=HTMLResponse)
def generate_workout(
    request: Request,
    user_id: str = Form(...),
    name: str = Form(...),
    age: str = Form(...),
    weight: str = Form(...),
    goal: str = Form(...),
    intensity: str = Form(...),
    db: Session = Depends(get_db),
):
    """Validate input, generate plan + tip with Gemini, save to SQLite, show result."""
    form_values = {"user_id": user_id, "name": name, "age": age,
                   "weight": weight, "goal": goal, "intensity": intensity}

    # 1) Validate the form
    try:
        data = UserInput(user_id=user_id, name=name, age=age, weight=weight,
                         goal=goal, intensity=intensity)
    except ValidationError as exc:
        return render_index(request, error=_friendly_validation(exc),
                            form=form_values, status_code=400)

    # 2) Generate the workout plan
    ok, plan = generate_workout_gemini(data.name, data.age, data.weight, data.goal, data.intensity)
    if not ok:
        return render_index(request, error=plan, form=form_values, status_code=502)

    # 3) Generate the nutrition / recovery tip (fallback tip if it fails)
    tip_ok, tip = generate_nutrition_tip_with_flash(data.goal, data.intensity, data.age, data.weight)
    if not tip_ok:
        tip = FALLBACK_TIP

    # 4) Save to the database (same User ID = replace that user's plan)
    try:
        record = db.query(UserWorkout).filter(UserWorkout.user_id == data.user_id).first()
        if record is None:
            record = UserWorkout(user_id=data.user_id)
            db.add(record)
        record.name = data.name
        record.age = data.age
        record.weight = data.weight
        record.goal = data.goal
        record.intensity = data.intensity
        record.original_plan = plan
        record.updated_plan = None
        record.nutrition_tip = tip
        db.commit()
        db.refresh(record)
    except SQLAlchemyError:
        db.rollback()
        return render_index(request, error=DB_ERROR, form=form_values, status_code=500)

    # 5) Show the result page
    return render_result(request, record, message="Your workout plan is ready!")


@router.post("/submit-feedback", response_class=HTMLResponse)
def submit_feedback(
    request: Request,
    user_id: str = Form(...),
    feedback: str = Form(...),
    db: Session = Depends(get_db),
):
    """Update the user's plan using their feedback and save it."""
    try:
        user = db.query(UserWorkout).filter(UserWorkout.user_id == user_id.strip()).first()
    except SQLAlchemyError:
        return render_index(request, error=DB_ERROR, status_code=500)

    # Validate feedback / user id
    try:
        data = FeedbackRequest(user_id=user_id, feedback=feedback)
    except ValidationError as exc:
        msg = _friendly_validation(exc)
        if user:
            return render_result(request, user, error=msg, status_code=400)
        return render_index(request, error=msg, status_code=400)

    if user is None:
        return render_index(
            request,
            error=f"No user found with User ID '{data.user_id}'. Please generate a workout first.",
            status_code=404,
        )

    # Use the latest version of the plan (updated one if it exists, else the original).
    base_plan = user.updated_plan or user.original_plan
    ok, new_plan = update_workout_plan(
        base_plan, data.feedback,
        goal=user.goal, intensity=user.intensity, age=user.age, weight=user.weight,
    )
    if not ok:
        return render_result(request, user, error=new_plan, status_code=502)

    try:
        user.updated_plan = new_plan
        db.commit()
        db.refresh(user)
    except SQLAlchemyError:
        db.rollback()
        return render_result(request, user, error=DB_ERROR, status_code=500)

    return render_result(request, user, message="Your workout plan has been updated!")


@router.get("/view-all-users", response_class=HTMLResponse)
def view_all_users(request: Request, db: Session = Depends(get_db)):
    """Simple admin page: show all users and their plans."""
    users, error = [], None
    try:
        users = db.query(UserWorkout).order_by(UserWorkout.created_at.desc()).all()
    except SQLAlchemyError:
        error = DB_ERROR
    return templates.TemplateResponse(
        request, "all_users.html", {"users": users, "error": error}
    )
